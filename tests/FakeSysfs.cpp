#include "FakeSysfs.h"
#include "SysfsReader.h"

#include <cstdlib>
#include <fstream>
#include <stdexcept>
#include <unistd.h>

namespace fs = std::filesystem;

namespace wct {

FakeSysfs::FakeSysfs()
{
    std::string tmpl = (fs::temp_directory_path() / "whatcable-test-XXXXXX").string();
    if (!::mkdtemp(tmpl.data()))
        throw std::runtime_error("mkdtemp failed");
    m_root = tmpl;
    WhatCable::SysfsReader::setRoot(m_root.string());
}

// Written into every kept tree; only a directory carrying it is replaced.
static const char kFixtureMarker[] = ".whatcable-fixture";

FakeSysfs::FakeSysfs(const fs::path &root)
    : m_root(fs::absolute(root)), m_keep(true)
{
    // Never delete a directory this class did not create: replace an
    // earlier fixture (marker present), accept a missing or empty
    // directory, and refuse anything else.
    if (fs::exists(m_root)) {
        if (!fs::is_directory(m_root))
            throw std::runtime_error(m_root.string() + " exists and is not a directory");
        if (fs::exists(m_root / kFixtureMarker))
            fs::remove_all(m_root);
        else if (!fs::is_empty(m_root))
            throw std::runtime_error(m_root.string() +
                                     " is not empty and is not a WhatCable fixture; refusing to replace it");
    }
    fs::create_directories(m_root);
    std::ofstream(m_root / kFixtureMarker) << "generated by whatcable-tests --write-fixture\n";
    WhatCable::SysfsReader::setRoot(m_root.string());
}

FakeSysfs::~FakeSysfs()
{
    WhatCable::SysfsReader::setRoot({});
    if (!m_keep) {
        std::error_code ec;
        fs::remove_all(m_root, ec);
    }
}

fs::path FakeSysfs::real(const std::string &path) const
{
    return m_root / fs::path(path).relative_path();
}

void FakeSysfs::write(const std::string &path, const std::string &value)
{
    writeBytes(path, value + "\n");
}

void FakeSysfs::writeBytes(const std::string &path, const std::string &bytes)
{
    const fs::path p = real(path);
    fs::create_directories(p.parent_path());
    std::ofstream out(p, std::ios::binary);
    out << bytes;
    if (!out)
        throw std::runtime_error("cannot write " + p.string());
}

void FakeSysfs::mkdir(const std::string &path)
{
    fs::create_directories(real(path));
}

void FakeSysfs::link(const std::string &path, const std::string &target)
{
    const fs::path p = real(path);
    fs::create_directories(p.parent_path());
    fs::create_directories(real(target));
    fs::create_directory_symlink(real(target), p);
}

} // namespace wct
